BEGIN;

ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS updated_by BIGINT;
ALTER TABLE solicitudes ADD COLUMN IF NOT EXISTS observaciones_resolucion TEXT;

CREATE TABLE IF NOT EXISTS auditoria_eventos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entidad TEXT NOT NULL CHECK (entidad IN ('usuario', 'solicitud')),
    entidad_id BIGINT NOT NULL,
    referencia TEXT NOT NULL,
    accion TEXT NOT NULL,
    actor_id BIGINT,
    actor_nombre TEXT,
    actor_rol TEXT,
    estado_anterior TEXT,
    estado_nuevo TEXT,
    observacion TEXT,
    fecha TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX IF NOT EXISTS auditoria_eventos_entidad_idx
    ON auditoria_eventos (entidad, entidad_id, id DESC);

CREATE OR REPLACE FUNCTION registrar_evento_operativo() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    evento auditoria_eventos%ROWTYPE;
BEGIN
    IF TG_TABLE_NAME = 'usuarios' THEN
        evento.entidad := 'usuario';
        evento.entidad_id := NEW.id_usuario;
        evento.referencia := NEW.nombre_completo;
        IF TG_OP = 'INSERT' THEN
            evento.accion := 'usuario_creado';
            evento.actor_id := NEW.created_by;
            evento.estado_nuevo := NEW.rol::TEXT;
        ELSE
            IF NEW.activo IS DISTINCT FROM OLD.activo THEN
                evento.accion := CASE WHEN NEW.activo THEN 'usuario_reactivado' ELSE 'usuario_desactivado' END;
            ELSIF NEW.nombre_completo IS DISTINCT FROM OLD.nombre_completo
                OR NEW.email_institucional IS DISTINCT FROM OLD.email_institucional
                OR NEW.rol IS DISTINCT FROM OLD.rol THEN
                evento.accion := 'usuario_actualizado';
            ELSE
                RETURN NEW;
            END IF;
            evento.actor_id := NEW.updated_by;
        END IF;
    ELSE
        evento.entidad := 'solicitud';
        evento.entidad_id := NEW.id_solicitud;
        evento.referencia := COALESCE(NEW.codigo_solicitud, NEW.id_solicitud::TEXT);
        evento.estado_nuevo := NEW.estado_solicitud::TEXT;
        IF TG_OP = 'INSERT' THEN
            evento.accion := 'solicitud_radicada';
            evento.actor_id := NEW.created_by;
        ELSE
            IF NEW.estado_solicitud IS NOT DISTINCT FROM OLD.estado_solicitud THEN
                RETURN NEW;
            END IF;
            evento.accion := 'solicitud_estado';
            evento.actor_id := NEW.updated_by;
            evento.estado_anterior := OLD.estado_solicitud::TEXT;
            evento.observacion := NEW.observaciones_resolucion;
        END IF;
    END IF;

    SELECT nombre_completo, rol::TEXT INTO evento.actor_nombre, evento.actor_rol
      FROM usuarios WHERE id_usuario = evento.actor_id;

    INSERT INTO auditoria_eventos (
      entidad, entidad_id, referencia, accion, actor_id, actor_nombre, actor_rol,
      estado_anterior, estado_nuevo, observacion
    ) VALUES (
      evento.entidad, evento.entidad_id, evento.referencia, evento.accion, evento.actor_id,
      evento.actor_nombre, evento.actor_rol, evento.estado_anterior, evento.estado_nuevo, evento.observacion
    );
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS auditoria_usuarios_operativa ON usuarios;
CREATE TRIGGER auditoria_usuarios_operativa
    AFTER INSERT OR UPDATE OF activo, nombre_completo, email_institucional, rol ON usuarios
    FOR EACH ROW EXECUTE FUNCTION registrar_evento_operativo();

DROP TRIGGER IF EXISTS auditoria_solicitudes_operativa ON solicitudes;
CREATE TRIGGER auditoria_solicitudes_operativa
    AFTER INSERT OR UPDATE OF estado_solicitud ON solicitudes
    FOR EACH ROW EXECUTE FUNCTION registrar_evento_operativo();

COMMIT;
